// Writes js/golden_data.js from the golden-case fixtures in tests/fixtures (brief §11), so Diagnostics
// can run the golden cases in the browser ("Run all tests") from the very same data the Node tests use.
// tests/unit.mjs (static) fails when js/golden_data.js is not current.
// Usage: node tools/build_golden.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(readFileSync(path.join(ROOT, "tests", "fixtures", f), "utf8"));

export function goldenText() {
  const data = { m100: read("m100.json"), g5: read("g5.json"), audit: read("audit-f01-f16.json") };
  return `// Generated by tools/build_golden.mjs from tests/fixtures (the golden cases of the brief's section 11).\n// Do not edit: change the fixtures and run the tool again.\nexport const GOLDEN = ${JSON.stringify(data, null, 1)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(ROOT, "js", "golden_data.js");
  const text = goldenText();
  if (process.argv.includes("--check")) {
    const ok = readFileSync(file, "utf8") === text;
    console.log(ok ? "GOLDEN CURRENT" : "GOLDEN STALE: run node tools/build_golden.mjs");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(file, text);
  console.log(`wrote ${path.relative(ROOT, file)} (${text.length} bytes)`);
}
